import fs from "fs";
import path from "path";

const directoryPath = path.join('lib', 'ts');  // Adjust the directory as needed
const pythonDirectoryPath = path.join('lib', 'py');
let exports = '';

// FlatBuffers field-encryption format 3 for TypeScript/JavaScript.
//
// flatc emits a buffer-level FlatbuffersEncryption helper for C#, Dart, Go,
// Java, Kotlin, Lobster, PHP, Python, Rust and Swift, but not for TypeScript.
// This runtime is the TypeScript counterpart: the same interpreter, run over
// the same "walk programs" flatc emits for those languages. The programs are
// read from flatc's Python output of the same build (lib/py), so the
// TypeScript helper can never disagree with the other languages about which
// field instances are encrypted.
const flatbuffersEncryptionRuntime = `// automatically generated by scripts/createTSIndex.js, do not modify

/* eslint-disable @typescript-eslint/no-unused-vars, @typescript-eslint/no-explicit-any, @typescript-eslint/no-non-null-assertion */

import initHDWallet from 'hd-wallet-wasm';

/**
 * FlatBuffers field-encryption format 3.
 *
 * Encrypts or decrypts, in place, every (encrypted) field instance of a buffer
 * exactly as the C++ walker (flatbuffers::EncryptBuffer/DecryptBuffer, version
 * 3), flatc-wasm and the FlatbuffersEncryption helpers flatc generates for the
 * other languages do: the record's key is
 * K = HKDF-SHA256(key, no salt, "flatbuffers-buffer-v3" || BE32(recordIndex)),
 * and each instance is AES-256-CTR encrypted with K and the IV
 * BE32(position of its first byte in the buffer) || 12 zero bytes, so no two
 * instances share a key stream. (key, recordIndex) must be unique per buffer.
 *
 * HKDF and AES run in hd-wallet-wasm, so browsers and Node.js share one
 * WASM/OpenSSL path.
 */

type HDWalletModule = {
  aesCtr: {
    encrypt(key: Uint8Array, plaintext: Uint8Array, iv: Uint8Array): Uint8Array;
  };
  utils: {
    hkdf(ikm: Uint8Array, salt: Uint8Array, info: Uint8Array, length: number): Uint8Array;
  };
};

let _wallet: Promise<HDWalletModule> | null = null;
function hdWallet(): Promise<HDWalletModule> {
  if (!_wallet) _wallet = initHDWallet() as unknown as Promise<HDWalletModule>;
  return _wallet;
}

/** The field-encryption format this helper reads and writes. */
export const FIELD_ENCRYPTION_VERSION = 3;

const BUFFER_KEY_LABEL = 'flatbuffers-buffer-v3';
const MAX_DEPTH = 64;

function fail(what: string): never {
  throw new Error('FlatbuffersEncryption: ' + what);
}

// One pass over a buffer by a table's walk program. Without a cipher it is the
// dry run that checks the whole buffer before any byte changes.
class Walk {
  private readonly view: DataView;
  private readonly size: number;
  private readonly tables = new Set<number>();
  private readonly regions = new Set<number>();

  constructor(
    private readonly buf: Uint8Array,
    private readonly program: readonly number[],
    private readonly cipher: ((start: number, length: number) => void) | null,
  ) {
    this.view = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
    this.size = buf.byteLength;
  }

  check(pos: number, length: number): void {
    if (pos < 0 || length < 0 || pos + length > this.size) {
      fail('the buffer is malformed (offset ' + pos + ' out of bounds)');
    }
  }

  private u8(pos: number): number {
    this.check(pos, 1);
    return this.buf[pos];
  }

  private u16(pos: number): number {
    this.check(pos, 2);
    return this.view.getUint16(pos, true);
  }

  private u32(pos: number): number {
    this.check(pos, 4);
    return this.view.getUint32(pos, true);
  }

  private i32(pos: number): number {
    this.check(pos, 4);
    return this.view.getInt32(pos, true);
  }

  private follow(pos: number): number {
    const target = pos + this.u32(pos);
    this.check(target, 4);
    return target;
  }

  private count(pos: number, elementSize: number): number {
    const n = this.u32(pos);
    this.check(pos + 4, n * elementSize);
    return n;
  }

  private crypt(start: number, length: number): void {
    if (length === 0 || this.regions.has(start)) return;
    this.regions.add(start);
    if (this.cipher) this.cipher(start, length);
  }

  private string(pos: number): void {
    const s = this.follow(pos);
    const n = this.u32(s);
    this.check(s + 4, n + 1);
    this.crypt(s + 4, n);
  }

  private field(table: number, slot: number): number {
    const vtable = table - this.i32(table);
    if (slot + 2 > this.u16(vtable)) return 0;
    const offset = this.u16(vtable + slot);
    return offset ? table + offset : 0;
  }

  private enter(table: number, depth: number): boolean {
    if (depth > MAX_DEPTH) fail('tables nested deeper than ' + MAX_DEPTH + ' levels');
    if (this.tables.has(table)) return false;
    this.tables.add(table);
    this.check(table, 4);
    const vtable = table - this.i32(table);
    this.check(vtable, 4);
    const vtableSize = this.u16(vtable);
    const tableSize = this.u16(vtable + 2);
    if (vtableSize < 4 || (vtableSize & 1) !== 0) fail('the buffer is malformed (bad vtable)');
    this.check(vtable, vtableSize);
    this.check(table, tableSize);
    for (let slot = 4; slot < vtableSize; slot += 2) {
      const offset = this.u16(vtable + slot);
      if (offset && offset >= tableSize) fail('the buffer is malformed (bad field offset)');
    }
    return true;
  }

  private member(at: number, n: number, type: number): number {
    const p = this.program;
    for (let i = 0; i < n; i += 1) {
      if (p[at + 2 * i] === type) return p[at + 2 * i + 1];
    }
    return -1;
  }

  walk(index: number, table: number, depth: number): void {
    if (!this.enter(table, depth)) return;
    const p = this.program;
    let at = p[1 + index];
    const ops = p[at];
    at += 1;
    for (let op = 0; op < ops; op += 1) {
      const kind = p[at];
      const slot = p[at + 1];
      at += 2;
      let arg = 0;
      let typeSlot = 0;
      let n = 0;
      let members = 0;
      if (kind === 0 || kind === 2 || kind === 4 || kind === 5) {
        arg = p[at];
        at += 1;
      } else if (kind === 6 || kind === 7) {
        typeSlot = p[at];
        n = p[at + 1];
        members = at + 2;
        at += 2 + 2 * n;
      } else if (kind !== 1 && kind !== 3) {
        fail('unknown walk program op ' + kind);
      }
      const loc = this.field(table, slot);
      if (loc === 0) continue;
      switch (kind) {
        case 0: // a scalar or a struct, in place
          this.check(loc, arg);
          this.crypt(loc, arg);
          break;
        case 1: // the bytes of a string
          this.string(loc);
          break;
        case 2: { // the elements of a vector of scalars or structs
          const v = this.follow(loc);
          this.crypt(v + 4, this.count(v, arg) * arg);
          break;
        }
        case 3: { // the bytes of each string of a vector
          const v = this.follow(loc);
          const count = this.count(v, 4);
          for (let i = 0; i < count; i += 1) this.string(v + 4 + 4 * i);
          break;
        }
        case 4: // a table
          this.walk(arg, this.follow(loc), depth + 1);
          break;
        case 5: { // each table of a vector
          const v = this.follow(loc);
          const count = this.count(v, 4);
          for (let i = 0; i < count; i += 1) this.walk(arg, this.follow(v + 4 + 4 * i), depth + 1);
          break;
        }
        case 6: { // a union
          const typeLoc = this.field(table, typeSlot);
          if (typeLoc === 0) break;
          const member = this.member(members, n, this.u8(typeLoc));
          if (member >= 0) this.walk(member, this.follow(loc), depth + 1);
          break;
        }
        case 7: { // a vector of unions
          const typeLoc = this.field(table, typeSlot);
          if (typeLoc === 0) break;
          const types = this.follow(typeLoc);
          const count = this.count(types, 1);
          const values = this.follow(loc);
          if (this.count(values, 4) !== count) fail('the buffer is malformed (union vectors differ)');
          for (let i = 0; i < count; i += 1) {
            const member = this.member(members, n, this.u8(types + 4 + i));
            if (member >= 0) this.walk(member, this.follow(values + 4 + 4 * i), depth + 1);
          }
          break;
        }
      }
    }
  }
}

export class FlatbuffersEncryption {
  /**
   * K = HKDF-SHA256(key, no salt, "flatbuffers-buffer-v3" || BE32(recordIndex)).
   */
  static async bufferKey(key: Uint8Array, recordIndex: number = 0): Promise<Uint8Array> {
    FlatbuffersEncryption.checkKey(key, recordIndex);
    const info = new Uint8Array(BUFFER_KEY_LABEL.length + 4);
    for (let i = 0; i < BUFFER_KEY_LABEL.length; i += 1) info[i] = BUFFER_KEY_LABEL.charCodeAt(i);
    new DataView(info.buffer).setUint32(BUFFER_KEY_LABEL.length, recordIndex, false);
    return (await hdWallet()).utils.hkdf(key, new Uint8Array(0), info, 32);
  }

  /**
   * Encrypts, or decrypts (the same operation), every (encrypted) field
   * instance of \`buffer\` in place by a table's walk program, and returns
   * \`buffer\`. \`buffer\` is the FlatBuffer without a size prefix. Rejects,
   * before any byte changes, a key that is not 32 bytes, a record index that
   * does not fit in 32 bits, or a malformed buffer.
   */
  static async cryptBuffer(
    buffer: Uint8Array,
    key: Uint8Array,
    recordIndex: number,
    program: readonly number[],
  ): Promise<Uint8Array> {
    FlatbuffersEncryption.checkKey(key, recordIndex);
    if (!(buffer instanceof Uint8Array) || buffer.byteLength < 4 || buffer.byteLength > 0x7fffffff) {
      fail('invalid buffer');
    }
    const root = new DataView(buffer.buffer, buffer.byteOffset, buffer.byteLength).getUint32(0, true);
    new Walk(buffer, program, null).check(root, 4);
    new Walk(buffer, program, null).walk(0, root, 0);
    const wallet = await hdWallet();
    const bufferKey = await FlatbuffersEncryption.bufferKey(key, recordIndex);
    try {
      new Walk(buffer, program, (start, length) => {
        const iv = new Uint8Array(16);
        new DataView(iv.buffer).setUint32(0, start, false);
        buffer.set(wallet.aesCtr.encrypt(bufferKey, buffer.subarray(start, start + length), iv), start);
      }).walk(0, root, 0);
    } finally {
      bufferKey.fill(0);
    }
    return buffer;
  }

  private static checkKey(key: Uint8Array, recordIndex: number): void {
    if (!(key instanceof Uint8Array) || key.byteLength !== 32) fail('the key must be 32 bytes');
    if (!Number.isInteger(recordIndex) || recordIndex < 0 || recordIndex > 0xffffffff) {
      fail('recordIndex must fit in 32 bits');
    }
  }
}
`;

// flatc's Python generator writes each table's walk program as
//   _FLATBUFFERS_ENCRYPTION_PROGRAM = (
//       1, 2, 1, 2, 12, 1
//   )
// in lib/py/<SCHEMA>/<Table>.py.
function readEncryptionPrograms(schemaName) {
    const folderPath = path.join(pythonDirectoryPath, schemaName);
    if (!fs.existsSync(folderPath)) {
        throw new Error(`createTSIndex: ${folderPath} is missing; run build:flatbuffers before build:js`);
    }
    const programs = new Map();
    for (const name of fs.readdirSync(folderPath).filter((file) => file.endsWith('.py')).sort()) {
        const source = fs.readFileSync(path.join(folderPath, name), 'utf8');
        const match = source.match(/_FLATBUFFERS_ENCRYPTION_PROGRAM = \(([\d,\s]+)\)/);
        if (!match) {
            continue;
        }
        const program = match[1].split(',').map((value) => value.trim()).filter(Boolean).map(Number);
        if (program.length === 0 || program.some((value) => !Number.isInteger(value))) {
            throw new Error(`createTSIndex: unreadable walk program in ${path.join(folderPath, name)}`);
        }
        programs.set(name.replace(/\.py$/, ''), program);
    }
    return programs;
}

function programLines(program) {
    const lines = [];
    for (let i = 0; i < program.length; i += 16) {
        lines.push(`    ${program.slice(i, i + 16).join(', ')}`);
    }
    return lines.join(',\n');
}

function flatbuffersEncryptionModule(programs) {
    const parts = [flatbuffersEncryptionRuntime];
    parts.push(
        '/**',
        ' * The walk program flatc emits for each table that has an (encrypted) field',
        ' * or reaches one through a table, a vector of tables or a union.',
        ' */',
        'export const FLATBUFFERS_ENCRYPTION_PROGRAMS: Readonly<Record<string, readonly number[]>> = {',
    );
    for (const [table, program] of programs) {
        parts.push(`  ${JSON.stringify(table)}: [\n${programLines(program)}\n  ],`);
    }
    parts.push('};', '');
    for (const table of programs.keys()) {
        const program = `FLATBUFFERS_ENCRYPTION_PROGRAMS[${JSON.stringify(table)}]`;
        parts.push(
            `/** Encrypts the (encrypted) fields of a ${table} buffer in place (key: 32 bytes; recordIndex: unique per buffer under the key). */`,
            `export function encrypt${table}Buffer(buffer: Uint8Array, key: Uint8Array, recordIndex: number = 0): Promise<Uint8Array> {`,
            `  return FlatbuffersEncryption.cryptBuffer(buffer, key, recordIndex, ${program});`,
            '}',
            '',
            `/** Decrypts the (encrypted) fields of a ${table} buffer in place (key: 32 bytes; recordIndex: the one it was encrypted with). */`,
            `export function decrypt${table}Buffer(buffer: Uint8Array, key: Uint8Array, recordIndex: number = 0): Promise<Uint8Array> {`,
            `  return FlatbuffersEncryption.cryptBuffer(buffer, key, recordIndex, ${program});`,
            '}',
            '',
        );
    }
    return parts.join('\n');
}

function ensureFlatbuffersEncryptionRuntime() {
    for (const dirent of fs.readdirSync(directoryPath, { withFileTypes: true })) {
        if (!dirent.isDirectory()) {
            continue;
        }
        const programs = readEncryptionPrograms(dirent.name);
        if (programs.size === 0) {
            continue;
        }
        fs.writeFileSync(
            path.join(directoryPath, dirent.name, 'flatbuffers-encryption.ts'),
            flatbuffersEncryptionModule(programs),
        );
    }
}

function writeFolderMain(folderPath) {
    const exportLines = fs
        .readdirSync(folderPath, { withFileTypes: true })
        .filter((dirent) => dirent.isFile())
        .map((dirent) => dirent.name)
        .filter((name) => name.endsWith('.ts'))
        .filter((name) => name !== 'main.ts' && name !== 'index.ts')
        .sort((left, right) => left.localeCompare(right))
        .map((name) => `export * from './${name.replace(/\.ts$/, '.js')}';`);

    const contents = [
        '// automatically generated by the FlatBuffers compiler, do not modify',
        '',
        '/* eslint-disable @typescript-eslint/no-unused-vars, @typescript-eslint/no-explicit-any, @typescript-eslint/no-non-null-assertion */',
        '',
        ...exportLines,
        '',
    ].join('\n');

    fs.writeFileSync(path.join(folderPath, 'main.ts'), contents);
}

ensureFlatbuffersEncryptionRuntime();

// Read all directory names under the specified path
fs.readdirSync(directoryPath, { withFileTypes: true })
    .filter(dirent => dirent.isDirectory())
    .forEach(dirent => {
        const folderName = dirent.name;
        writeFolderMain(path.join(directoryPath, folderName));
        exports += `export * as ${folderName.toUpperCase()} from './${folderName}/main.js';\n`;
    });

// Write the master index.ts file
fs.writeFileSync(path.join(directoryPath, 'index.ts'), exports);
